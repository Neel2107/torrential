#!/bin/sh
# Checks changes against the mistakes this repo has made. It fails when a change adds build output,
# changes web/src/wire.ts without a crates/ change (wire.ts is generated from the engine), raises or
# drops a ceiling (--max-warnings, --max) in mobile/package.json, or raises a budget or drops a budgeted
# scenario in mobile/src/perf/budgets.ts or mobile/src/perf/bundle.json. It warns on a commit subject
# longer than 72 characters.
#
#   mobile/scripts/guard.sh [<base>] [<head>]     each commit in base..head (default origin/mobile HEAD)
#   mobile/scripts/guard.sh --staged              what is staged for the next commit
#
# Merge commits are skipped; the commits they bring in are checked. A base that is empty, all zeros or
# unknown (a new branch) checks <head> alone. A base that is not an ancestor of <head> (a force push)
# checks from where the two diverged. A change that has to raise a ceiling says why on a line starting
# "Raises-ceiling:" in its commit body; the guard then warns instead of failing.
set -eu

limit=72
build_output='(^|/)build/|(^|/)node_modules/|\.apk$|\.so$|\.hbc$|\.xcframework/|^mobile/(android|ios)/'
failures=0
warnings=0

report() {
  level=$1
  shift
  if [ "${GITHUB_ACTIONS:-}" = true ]; then
    echo "::$level title=guard::$*"
  else
    echo "guard: $level: $*"
  fi
}

fail() {
  report error "$@"
  failures=$((failures + 1))
}

warn() {
  report warning "$@"
  warnings=$((warnings + 1))
}

chars() {
  printf '%s' "$1" | LC_ALL=C tr -d '\200-\277' | wc -c | tr -d ' '
}

ceiling() {
  git show "$1mobile/package.json" 2>/dev/null | grep -o -- "$2 [0-9][0-9]*" | cut -d' ' -f2 | sort -n | tail -1
}

budgets() {
  git show "$1mobile/src/perf/budgets.ts" 2>/dev/null | awk -F"'" '/scenario: .*route: .*requests: [0-9]+, chars: [0-9]+/ {
    requests = $0; sub(/.*requests: /, "", requests)
    chars = $0; sub(/.*chars: /, "", chars)
    print $2 " | " $4 " | requests = " requests + 0
    print $2 " | " $4 " | characters = " chars + 0
  }'
  git show "$1mobile/src/perf/bundle.json" 2>/dev/null | awk -F'"' '/"[a-z]+": *[0-9]+/ {
    bytes = $3; gsub(/[^0-9]/, "", bytes)
    print "bundle | " $2 " | bytes = " bytes + 0
  }'
}

raised_budgets() {
  { echo '#old'; budgets "$1"; echo '#new'; budgets "$2"; } | awk '
    /^#old$/ { side = "old"; next }
    /^#new$/ { side = "new"; next }
    {
      at = index($0, " = "); key = substr($0, 1, at - 1); value = substr($0, at + 3) + 0
      group = substr(key, 1, index(key, " | ") - 1)
      if (side == "old") { before[key] = value; was[group] = 1 } else { after[key] = value; is[group] = 1 }
    }
    END {
      for (key in after) {
        group = substr(key, 1, index(key, " | ") - 1)
        if (key in before) { if (after[key] > before[key]) print "raises the budget " key " from " before[key] " to " after[key] }
        else if (group in was) print "raises the budget " key " from 0 to " after[key]
      }
      for (group in was) if (!(group in is)) print "drops every budget of \"" group "\""
    }' | sort
}

check() {
  label=$1 added=$2 changed=$3 old=$4 new=$5 reason=$6

  found=$(printf '%s\n' "$added" | grep -E "$build_output" || true)
  if [ -n "$found" ]; then
    count=$(printf '%s\n' "$found" | wc -l | tr -d ' ')
    roots=$(printf '%s\n' "$found" | sed -E 's#^((.*/)?(build|node_modules|[^/]*\.xcframework)/).*#\1#; s#^(mobile/(android|ios)/).*#\1#' |
      sort -u | head -5 | tr '\n' ' ')
    fail "$label adds build output ($count files): ${roots% }"
  fi

  if printf '%s\n' "$changed" | grep -qx 'web/src/wire.ts' && ! printf '%s\n' "$changed" | grep -q '^crates/'; then
    fail "$label changes web/src/wire.ts without a crates/ change; wire.ts is generated by the engine's tests"
  fi

  if [ -n "$old" ] && printf '%s\n' "$changed" | grep -qx 'mobile/package.json'; then
    for flag in --max-warnings --max; do
      before=$(ceiling "$old" "$flag")
      after=$(ceiling "$new" "$flag")
      [ -n "$before" ] || continue
      if [ -z "$after" ]; then
        problem="drops the $flag ceiling ($before) from mobile/package.json"
      elif [ "$after" -gt "$before" ]; then
        problem="raises $flag from $before to $after in mobile/package.json"
      else
        continue
      fi
      if [ -n "$reason" ]; then
        warn "$label $problem: $reason"
      else
        fail "$label $problem; fix the cause, or say why on a Raises-ceiling: line"
      fi
    done
  fi

  if [ -n "$old" ] && printf '%s\n' "$changed" | grep -qxE 'mobile/src/perf/(budgets\.ts|bundle\.json)'; then
    raised=$(raised_budgets "$old" "$new")
    [ -n "$raised" ] || return 0
    printf '%s\n' "$raised" | while IFS= read -r problem; do
      if [ -n "$reason" ]; then
        report warning "$label $problem: $reason"
      else
        report error "$label $problem; fix the cause, or say why on a Raises-ceiling: line"
      fi
    done
    count=$(printf '%s\n' "$raised" | wc -l | tr -d ' ')
    if [ -n "$reason" ]; then
      warnings=$((warnings + count))
    else
      failures=$((failures + count))
    fi
  fi
}

if [ "${1:-}" = --staged ]; then
  old=
  git rev-parse --verify --quiet HEAD >/dev/null && old=HEAD:
  check "the staged change" "$(git diff --cached --diff-filter=A --name-only)" \
    "$(git diff --cached --name-only)" "$old" ":" ""
  [ "$failures" -eq 0 ] || echo "guard: unstage it, or commit with --no-verify if you are sure" >&2
  [ "$failures" -eq 0 ]
  exit
fi

head=$(git rev-parse --verify --quiet "${2:-HEAD}^{commit}") || {
  echo "guard: no commit ${2:-HEAD}" >&2
  exit 2
}
base=${1-origin/mobile}

if [ -n "$base" ] && from=$(git rev-parse --verify --quiet "$base^{commit}") &&
  from=$(git merge-base "$from" "$head"); then
  commits=$(git rev-list --no-merges --reverse "$from..$head")
  range="$(git rev-parse --short "$from")..$(git rev-parse --short "$head")"
else
  commits=$(git rev-list --no-merges -1 "$head")
  range="$(git rev-parse --short "$head") alone (no usable base: '${base}')"
fi

checked=0
for commit in $commits; do
  checked=$((checked + 1))
  short=$(git rev-parse --short "$commit")
  subject=$(git log -1 --format=%s "$commit")

  length=$(chars "$subject")
  if [ "$length" -gt "$limit" ]; then
    warn "$short subject is $length characters (limit $limit): $subject"
  fi

  old=
  git rev-parse --verify --quiet "$commit^" >/dev/null && old="$commit^:"
  check "$short" \
    "$(git diff-tree --root --no-commit-id -r --diff-filter=A --name-only "$commit")" \
    "$(git diff-tree --root --no-commit-id -r --name-only "$commit")" \
    "$old" "$commit:" \
    "$(git log -1 --format=%b "$commit" | sed -n 's/^Raises-ceiling: *//p' | head -1)"
done

echo "guard: $checked commits in $range: $failures failed, $warnings warnings"
[ "$failures" -eq 0 ]
